def buscar_significado(nombre_archivo):
    """Busca el significado de una carta por el nombre de su archivo."""
    # Quitamos la extensión y normalizamos
    clave = nombre_archivo.lower()
    for ext in ['.jpg', '.jpeg', '.png']:
        clave = clave.replace(ext, '')

    # Quitamos timestamps (ej: 00_el_loco_1786811665037 -> 00_el_loco)
    import re
    clave = re.sub(r'_\d{10,}$', '', clave)

    return SIGNIFICADOS.get(clave, {
        "nombre": nombre_archivo,
        "normal": "Esta carta guarda sus secretos para quien sabe escuchar.",
        "invertida": "El misterio se profundiza cuando la carta se voltea."
    })
